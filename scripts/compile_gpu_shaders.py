"""Compile and embed the PS4 direct-binning shader reproducibly."""
from pathlib import Path
import struct, subprocess
root = Path('/work')
output = root / 'build/gpu-shaders'
output.mkdir(parents=True, exist_ok=True)
shader = root / 'src/gpu_shaders/tile_binning_direct.comp'
includes = root / 'vendor/parallel-n64/mupen64plus-video-paraLLEl/parallel-rdp/parallel-rdp/shaders'
binary = output / 'tile_binning_direct.spv'
subprocess.run([str(root / 'build/gpu/glslang-host/StandAlone/glslang'), '-V',
    '--target-env', 'vulkan1.1', '-I' + str(includes), str(shader), '-o', str(binary)], check=True)
data = binary.read_bytes()
words = struct.unpack('<%dI' % (len(data)//4), data)
# Audit the resulting module, not just the GLSL source.
i = 5
while i < len(words):
    size, opcode = words[i] >> 16, words[i] & 0xffff
    assert size > 0
    assert opcode not in {224, 225, 318, 319, *range(227, 243)}, 'Unexpected barrier or atomic instruction'
    if opcode == 59:  # OpVariable: storage class Workgroup = 4
        assert words[i+3] != 4, 'Unexpected LDS variable'
    i += size
assert i == len(words)
header = '// Generated by scripts/compile_gpu_shaders.py; do not edit.\n#pragma once\n#include <stdint.h>\nnamespace RDP {\nstatic const uint32_t nps64_tile_direct_spirv[] = {\n'
for i in range(0,len(words),8):
    header += '    ' + ', '.join('0x%08xu' % w for w in words[i:i+8]) + ',\n'
header += '};\n}\n'
(root / 'src/gpu_shaders/tile_binning_direct_spv.hpp').write_text(header, encoding='utf-8')
print('PASS: embedded direct-binning SPIR-V contains no LDS, atomics or barriers (%d bytes)' % len(data))

# Color-only variant: preserve upstream raster/shading/blending and specialize
# away texture paths only when the CPU verifies every state in the batch.
shading = (includes / 'shading.h').read_text()
for name, bit in [('copy_en','RASTERIZATION_COPY_BIT'),
                  ('uses_texel0','RASTERIZATION_USES_TEXEL0_BIT'),
                  ('uses_texel1','RASTERIZATION_USES_TEXEL1_BIT'),
                  ('uses_pipelined_texel1','RASTERIZATION_USES_PIPELINED_TEXEL1_BIT'),
                  ('uses_lod','RASTERIZATION_USES_LOD_BIT')]:
    old = f'bool {name} = (static_state_flags & {bit}) != 0;'
    assert shading.count(old) == 1, old
    shading = shading.replace(old, f'bool {name} = false; // NPS64 CPU-checked color-only batch.')
(output / 'nps64_color_shading.h').write_text(shading)
source = (includes / 'ubershader.comp').read_text()
source = source.replace('#version 450', '#version 450\n#extension GL_GOOGLE_include_directive : require\n#define SMALL_TYPES 0\n#define SUBGROUP 0\n#define DEBUG_ENABLE 0', 1)
source = source.replace('#include "shading.h"', '#include "nps64_color_shading.h"')
glsl = output / 'color_raster.comp'; glsl.write_text(source)
binary = output / 'color_raster.spv'
subprocess.run([str(root / 'build/gpu/glslang-host/StandAlone/glslang'), '-V',
    '--target-env', 'vulkan1.1', '-I' + str(includes), str(glsl), '-o', str(binary)], check=True)
data = binary.read_bytes(); words = struct.unpack('<%dI' % (len(data)//4), data)
header = '// Generated by scripts/compile_gpu_shaders.py; do not edit.\n#pragma once\n#include <stdint.h>\nnamespace RDP {\nstatic const uint32_t nps64_color_spirv[] = {\n'
for i in range(0,len(words),8):
    header += '    ' + ', '.join('0x%08xu' % w for w in words[i:i+8]) + ',\n'
header += '};\n}\n'
(root / 'src/gpu_shaders/color_raster_spv.hpp').write_text(header, encoding='utf-8')
print('PASS: generated CPU-guarded color-only raster shader (%d bytes)' % len(data))
